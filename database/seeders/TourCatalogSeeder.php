                if ($categoryId === null) {
                    throw new \RuntimeException('Сначала импортируйте схему TryTravel с категориями.');
                }

                foreach ($offers as $offer) {
                    [$title, $country, $destination, $date, $nights, $meal, $price, $image] = $offer;
                    $description = isset($offer[8])
                        ? $offer[8]."\n\nУчебный пакет. Даты, цены и питание указаны для демонстрации. Фото иллюстрирует направление."
                        : 'Демонстрационное предложение из макета TryTravel.';
                    $location = ['country' => $country, 'name' => $destination];
                    $destinationId = DB::table('destinations')->where($location)->value('destination_id')
                        ?? DB::table('destinations')->insertGetId($location, 'destination_id');

                    $identity = [
                        'category_id' => $categoryId,
                        'destination_id' => $destinationId,
                        'title' => $title,
                        'departure_city' => 'Томск',
                        'departure_date' => $date,
                    ];

                    $tourId = DB::table('tours')->where($identity)->value('tour_id');
                    if ($tourId === null) {
                        $tourId = DB::table('tours')->insertGetId($identity + [
                            'nights' => $nights,
                            'meal_plan' => $meal,
                            'price' => $price,
                            'image_url' => 'images/'.$image,
                            'description' => $description,
                        ], 'tour_id');
                    }

                    DB::table('tour_guest_limits')->insertOrIgnore([
                        'tour_id' => $tourId,
                        'max_adults' => 2,
                        'max_children' => $nights % 3,
                    ]);
                }
            }
